def click(selector):b.evaluate('document.querySelector('+json.dumps(selector)+').click()')
def audio(selector):
    result=b.evaluate('''(async()=>{const a=document.querySelector(SELECTOR);a.load();await new Promise((resolve,reject)=>{if(a.readyState>=1)resolve();else{a.onloadedmetadata=resolve;a.onerror=()=>reject(new Error('audio error'));}});await a.play();await new Promise(r=>setTimeout(r,250));const result={duration:a.duration,playing:!a.paused,time:a.currentTime,error:a.error?.code||null};a.pause();return result;})()'''.replace('SELECTOR',json.dumps(selector)))
    assert result['playing'] and result['duration']>0 and result['time']>0 and not result['error'],result
    return result
